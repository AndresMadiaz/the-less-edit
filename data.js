/** Validate authored records at build time; this does not infer or score product matches. */
export function validateCatalogue() {
  const errors = [];
  const productIds = new Set();
  const comparisonIds = new Set();
  const slugs = new Set();
  const requiredProductFields = [
    "id", "brand", "exactName", "retailer", "productUrl", "imageUrl", "priceAmount", "currency",
    "lastCheckedAt", "availabilityStatus", "colour", "materialComposition", "category", "fitNotes",
    "visibleTraits", "editorialNotes", "isReference"
  ];
  const nullableTextFields = [
    "brand", "exactName", "retailer", "productUrl", "imageUrl", "lastCheckedAt", "colour", "materialComposition", "fitNotes"
  ];
  const isText = (value) => typeof value === "string" && value.trim().length > 0;
  const isNullableText = (value) => value === null || isText(value);
  const isWebUrl = (value) => {
    if (!value) return true;
    try { return ["http:", "https:"].includes(new URL(value).protocol); }
    catch { return false; }
  };
  const isIsoDate = (value) => {
    if (typeof value !== "string" || !/^\d{4}-\d{2}-\d{2}$/.test(value)) return false;
    const date = new Date(`${value}T00:00:00Z`);
    return !Number.isNaN(date.valueOf()) && date.toISOString().slice(0, 10) === value;
  };

  for (const product of products) {
    for (const field of requiredProductFields) {
      if (!Object.hasOwn(product, field)) errors.push(`Product ${product.id || "(missing id)"} is missing ${field}.`);
    }
    if (!isText(product.id) || productIds.has(product.id)) errors.push(`Product id is missing or duplicated: ${product.id || "(empty)"}.`);
    productIds.add(product.id);
    for (const field of ["category"]) {
      if (!isText(product[field])) errors.push(`Product ${product.id} needs a non-empty ${field}.`);
    }
    for (const field of nullableTextFields) {
      if (!isNullableText(product[field])) errors.push(`Product ${product.id} has an invalid ${field}; use text or null.`);
    }
    if (product.priceAmount !== null && (!Number.isFinite(product.priceAmount) || product.priceAmount < 0)) errors.push(`Product ${product.id} has an invalid priceAmount.`);
    if (product.currency !== null && !/^[A-Z]{3}$/.test(product.currency || "")) errors.push(`Product ${product.id} currency must be a three-letter ISO code or null.`);
    if (product.priceAmount !== null && !/^[A-Z]{3}$/.test(product.currency || "")) errors.push(`Product ${product.id} needs an ISO currency when a price is present.`);
    if (!availabilityStatuses.includes(product.availabilityStatus)) errors.push(`Product ${product.id} has an unsupported availabilityStatus.`);
    if (product.lastCheckedAt !== null && !isIsoDate(product.lastCheckedAt)) errors.push(`Product ${product.id} lastCheckedAt must use YYYY-MM-DD or null.`);
    if (!Array.isArray(product.visibleTraits) || !product.visibleTraits.every(isText)) errors.push(`Product ${product.id} visibleTraits must be text entries.`);
    if (!Array.isArray(product.editorialNotes) || !product.editorialNotes.every(isText)) errors.push(`Product ${product.id} editorialNotes must be text entries.`);
    if (typeof product.isReference !== "boolean" || typeof product.isIllustrative !== "boolean") errors.push(`Product ${product.id} needs explicit reference and provenance flags.`);
    if (!isWebUrl(product.productUrl)) errors.push(`Product ${product.id} productUrl must use http(s).`);
    if (product.imageUrl && !(product.imageUrl.startsWith("/") && !product.imageUrl.startsWith("//")) && !isWebUrl(product.imageUrl)) errors.push(`Product ${product.id} imageUrl must be a site path or http(s) URL.`);
  }

  for (const comparison of comparisons) {
    const alternativeIds = Array.isArray(comparison.alternativeProductIds) ? comparison.alternativeProductIds : [];
    const requiredComparisonFields = [
      "id", "slug", "title", "referenceProductId", "alternativeProductIds", "featuredAlternativeId",
      "styleTags", "matches", "differences", "editorialReason", "confidenceLevel", "sourceCompleteness"
    ];
    for (const field of requiredComparisonFields) {
      if (!Object.hasOwn(comparison, field)) errors.push(`Comparison ${comparison.id || "(missing id)"} is missing ${field}.`);
    }
    if (!isText(comparison.id) || comparisonIds.has(comparison.id)) errors.push(`Comparison id is missing or duplicated: ${comparison.id || "(empty)"}.`);
    comparisonIds.add(comparison.id);
    if (!isText(comparison.slug) || slugs.has(comparison.slug)) errors.push(`Comparison slug is missing or duplicated: ${comparison.slug || "(empty)"}.`);
    slugs.add(comparison.slug);
    if (!isText(comparison.title) || !isText(comparison.editorialReason)) errors.push(`Comparison ${comparison.id} needs a title and editorialReason.`);
    if (!Number.isFinite(comparison.sortOrder)) errors.push(`Comparison ${comparison.id} needs a numeric sortOrder for editorial display.`);
    if (!Array.isArray(comparison.alternativeProductIds) || !alternativeIds.length) errors.push(`Comparison ${comparison.id} needs at least one alternativeProductId.`);
    if (new Set(alternativeIds).size !== alternativeIds.length) errors.push(`Comparison ${comparison.id} has duplicate alternativeProductIds.`);
    if (!Array.isArray(comparison.styleTags) || !comparison.styleTags.every(isText)) errors.push(`Comparison ${comparison.id} styleTags must be text entries.`);
    if (!Array.isArray(comparison.matches) || !comparison.matches.every(isText)) errors.push(`Comparison ${comparison.id} matches must be text entries.`);
    if (!Array.isArray(comparison.differences) || !comparison.differences.every(isText)) errors.push(`Comparison ${comparison.id} differences must be text entries.`);
    if (!comparisonConfidenceLevels.includes(comparison.confidenceLevel)) errors.push(`Comparison ${comparison.id} has an unsupported confidenceLevel.`);
    if (!comparisonSourceCompleteness.includes(comparison.sourceCompleteness)) errors.push(`Comparison ${comparison.id} has an unsupported sourceCompleteness.`);
    if (!productIds.has(comparison.referenceProductId)) errors.push(`Comparison ${comparison.id} references a missing reference product.`);
    if (!alternativeIds.includes(comparison.featuredAlternativeId)) errors.push(`Comparison ${comparison.id} featuredAlternativeId must be one of its alternatives.`);
    for (const productId of alternativeIds) {
      if (!productIds.has(productId)) errors.push(`Comparison ${comparison.id} references missing alternative ${productId}.`);
    }
    if (comparison.alternativeEditorialNotes !== undefined && (!comparison.alternativeEditorialNotes || Array.isArray(comparison.alternativeEditorialNotes) || typeof comparison.alternativeEditorialNotes !== "object")) {
      errors.push(`Comparison ${comparison.id} alternativeEditorialNotes must be an object keyed by alternative product id.`);
    }
    for (const [alternativeId, notes] of Object.entries(comparison.alternativeEditorialNotes || {})) {
      if (!alternativeIds.includes(alternativeId)) errors.push(`Comparison ${comparison.id} has notes for an unlisted alternative ${alternativeId}.`);
      if (!notes || !Array.isArray(notes.matches) || !notes.matches.every(isText) || !Array.isArray(notes.differences) || !notes.differences.every(isText)) {
        errors.push(`Comparison ${comparison.id} notes for ${alternativeId} need matches and differences text arrays.`);
      }
    }
  }

  if (errors.length) throw new Error(`Invalid Less Edit catalogue:\n- ${errors.join("\n- ")}`);
  return true;
}
